const COLOR_MAP = Object.fromEntries(COLOR_PALETTE.map(c => [c.name.toLowerCase(), c.hex]));

export function colorHex(name = '') {
  if (!name) return null;
  return COLOR_MAP[String(name).trim().toLowerCase()] || null;
}

// Parses the stored colors column ('Red, Blue' | 'Available in all colors') into dots.
// Returns [{ name?, hex? }] or [{ all: true }] for the "every color" sentinel.
export function parseColors(value) {
  if (!value) return [];
  if (String(value).toLowerCase() === 'available in all colors') return [{ all: true }];
  return String(value)
    .split(',')
    .map(s => s.trim())
    .filter(Boolean)
    .map(name => ({ name, hex: colorHex(name) }));
}
